from tools.utils.sysinfo.bench import store
from tools.utils.sysinfo.bench.record import LIB
from tools.utils.sysinfo.formatting import memory_capacity

HEADER = "<!-- generated by sysinfo bench document; do not edit -->\n"


def format_value(value):
    if value is None:
        return "—"
    if abs(value) >= 1000:
        return f"{value:,.0f}".replace(",", " ")
    if abs(value) >= 10:
        return f"{value:.1f}"
    return f"{value:.2f}"


def describe_hardware(snapshot):
    cpu = snapshot.get("cpu") or {}
    parts = [cpu.get("model", "")]
    for gpu in snapshot.get("gpu") or []:
        if gpu.get("type") == "Discrete":
            parts.append(gpu.get("name", ""))
    memory = snapshot.get("memory") or {}
    if memory.get("total"):
        parts.append(memory_capacity(memory["total"]))
    return ", ".join(part for part in parts if part)


def epoch_section(host, epoch, runs, baseline):
    latest = runs[0]
    lines = [f"### `{epoch}`\n\n", f"{describe_hardware(latest.snapshot)}\n\n"]
    if baseline:
        lines.append(f"Baseline: `{baseline}`\n\n")
    keys = sorted({metric.key for run in runs for metric in run.metrics})
    if not keys:
        return lines
    lines.append("| metric | unit | latest | runs | best |\n")
    lines.append("| --- | --- | --- | --- | --- |\n")
    for key in keys:
        present = [
            metric
            for metric in (run.metric(key) for run in runs)
            if metric and metric.median is not None
        ]
        if not present:
            continue
        medians = [metric.median for metric in present]
        best = min(medians) if present[0].proportion == LIB else max(medians)
        lines.append(
            f"| `{key}` | {present[0].scale} | {format_value(present[0].median)} | "
            f"{len(present)} | {format_value(best)} |\n"
        )
    lines.append("\n")
    return lines


def render():
    hosts = store.known_hosts()
    if not hosts:
        return ""
    baselines = store.load_baselines()
    parts = [HEADER, "\n# Benchmarks\n"]
    for host in hosts:
        runs = store.list_runs(host, grades=("clean",))
        if not runs:
            continue
        parts.append(f"\n## `{host}`\n\n")
        installs = sorted({run.install.get("os", "unknown") for run in runs})
        noun = "run" if len(runs) == 1 else "runs"
        parts.append(f"{len(runs)} clean {noun}  |  {', '.join(installs)}\n\n")
        by_epoch = {}
        for run in runs:
            by_epoch.setdefault(run.epoch, []).append(run)
        for epoch in sorted(by_epoch, key=lambda key: by_epoch[key][0].started, reverse=True):
            parts.extend(
                epoch_section(host, epoch, by_epoch[epoch], baselines.get(host, {}).get(epoch, ""))
            )
    return "".join(parts)


def write():
    path = store.benchmarks_dir() / store.DOCUMENT
    content = render()
    previous = ""
    if path.is_file():
        with open(path, encoding="utf-8") as handle:
            previous = handle.read()
    if previous == content:
        return path, False
    if not content:
        if path.is_file():
            path.unlink()
            return path, True
        return path, False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return path, True
