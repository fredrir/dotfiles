use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;

use super::plan::Output;
use crate::context::Context;
use sysinfo::bench::{
    compare,
    record::{CLEAN, LIB, Run},
    store::{Baselines, Store},
};

const NAME: &str = "BENCHMARKS.md";
const MARKER: &str = "<!-- generated by dotfile docs; do not edit -->";
const LEGACY_MARKER: &str = "<!-- generated by sysinfo bench document; do not edit -->";

fn number(value: f64) -> String {
    if value.abs() >= 1000.0 {
        let rounded = format!("{value:.0}");
        let digits = rounded.trim_start_matches('-');
        let grouped = digits
            .chars()
            .enumerate()
            .fold(String::new(), |mut result, (i, digit)| {
                if i > 0 && (digits.len() - i).is_multiple_of(3) {
                    result.push(' ');
                }
                result.push(digit);
                result
            });
        format!(
            "{}{grouped}",
            if value.is_sign_negative() { "-" } else { "" }
        )
    } else if value.abs() >= 10.0 {
        format!("{value:.1}")
    } else {
        format!("{value:.2}")
    }
}

fn hardware(run: &Run) -> String {
    let mut parts = vec![
        run.snapshot["cpu"]["model"]
            .as_str()
            .unwrap_or("")
            .to_string(),
    ];
    for gpu in run.snapshot["gpu"].as_array().into_iter().flatten() {
        if gpu["type"] == "Discrete" {
            parts.push(gpu["name"].as_str().unwrap_or("").into());
        }
    }
    if let Some(bytes) = run.snapshot["memory"]["total"]
        .as_f64()
        .filter(|bytes| *bytes > 0.0)
    {
        parts.push(sysinfo::formatting::memory_capacity(bytes));
    }
    parts
        .into_iter()
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join(", ")
}

fn render(runs: &[Run], baselines: &Baselines) -> String {
    if runs.is_empty() {
        return String::new();
    }
    let mut hosts = BTreeMap::<&str, Vec<&Run>>::new();
    for run in runs {
        hosts.entry(&run.host).or_default().push(run);
    }
    let mut text = format!("{MARKER}\n\n# Benchmarks\n");
    for (host, mut runs) in hosts {
        runs.sort_by(|a, b| {
            b.started
                .cmp(&a.started)
                .then_with(|| b.run_id.cmp(&a.run_id))
        });
        let installs = runs
            .iter()
            .map(|run| run.install["os"].as_str().unwrap_or("unknown"))
            .collect::<BTreeSet<_>>();
        text.push_str(&format!(
            "\n## `{host}`\n\n{} clean {}  |  {}\n\n",
            runs.len(),
            if runs.len() == 1 { "run" } else { "runs" },
            installs.into_iter().collect::<Vec<_>>().join(", ")
        ));
        let mut epochs = BTreeMap::<String, Vec<&Run>>::new();
        for run in runs {
            epochs.entry(run.epoch()).or_default().push(run);
        }
        let mut epochs = epochs.into_iter().collect::<Vec<_>>();
        epochs.sort_by(|a, b| {
            b.1[0]
                .started
                .cmp(&a.1[0].started)
                .then_with(|| a.0.cmp(&b.0))
        });
        for (epoch, runs) in epochs {
            text.push_str(&format!("### `{epoch}`\n\n{}\n\n", hardware(runs[0])));
            if let Some(id) = baselines.get(host).and_then(|entries| entries.get(&epoch)) {
                text.push_str(&format!("Baseline: `{id}`\n\n"));
            }
            let keys = runs
                .iter()
                .flat_map(|run| run.metrics.iter().map(|metric| metric.key.as_str()))
                .collect::<BTreeSet<_>>();
            let mut rows = Vec::new();
            for key in keys {
                let Some((latest_run, latest, value)) = runs.iter().find_map(|run| {
                    let metric = run.metric(key)?;
                    Some((*run, metric, metric.median()?))
                }) else {
                    continue;
                };
                let values = runs
                    .iter()
                    .filter_map(|run| {
                        let metric = run.metric(key)?;
                        if metric.scale != latest.scale || metric.proportion != latest.proportion {
                            return None;
                        }
                        if run.run_id != latest_run.run_id
                            && !compare::blocking_reason(latest_run, run, latest, metric).is_empty()
                        {
                            return None;
                        }
                        metric.median()
                    })
                    .collect::<Vec<_>>();
                let best = values
                    .iter()
                    .copied()
                    .reduce(if latest.proportion == LIB {
                        f64::min
                    } else {
                        f64::max
                    })
                    .unwrap_or(value);
                rows.push(vec![
                    format!("`{key}`"),
                    latest.scale.clone(),
                    number(value),
                    values.len().to_string(),
                    number(best),
                ]);
            }
            if !rows.is_empty() {
                text.push_str(&super::markdown::table(
                    &["Metric", "Unit", "Latest", "Runs", "Best"],
                    &rows,
                ));
                text.push_str("\n\n");
            }
        }
    }
    text
}

pub(super) fn output(context: &Context) -> Result<Output, String> {
    let directory = context
        .env("SYSINFO_BENCHMARKS")
        .map(PathBuf::from)
        .unwrap_or_else(|| context.root.join("benchmarks"));
    let directory = if directory.is_absolute() {
        directory
    } else {
        std::env::current_dir()
            .map_err(|e| e.to_string())?
            .join(directory)
    };
    let store = Store::new(directory.clone());
    let runs = store.list_runs(None, CLEAN)?;
    let baselines = store.load_baselines()?;
    let previous = super::plan::read(&directory.join(NAME))?;
    if !previous.is_empty()
        && !previous
            .lines()
            .any(|line| line == MARKER || line == LEGACY_MARKER)
    {
        return Err(format!(
            "{}: generated marker missing",
            directory.join(NAME).display()
        ));
    }
    let content = render(&runs, &baselines);
    let output = if content.is_empty() {
        Output::remove(NAME.into())
    } else {
        Output::text(NAME, content)
    };
    if let Ok(relative) = directory.strip_prefix(&context.root) {
        Ok(if let Some(content) = output.content {
            Output::text(
                relative.join(NAME),
                String::from_utf8(content).map_err(|e| e.to_string())?,
            )
        } else {
            Output::remove(relative.join(NAME))
        })
    } else {
        Ok(output.in_directory(directory))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use sysinfo::bench::record::Metric;

    #[test]
    fn different_methods_do_not_share_a_best_score() {
        let metric = |method: &str, value| Metric {
            key: "cpu.test".into(),
            method: method.into(),
            scale: "ops/s".into(),
            samples: vec![value],
            ..Default::default()
        };
        let old = Run {
            host: "host".into(),
            run_id: "old".into(),
            started: "2025".into(),
            metrics: vec![metric("tool/1.0", 9999.0)],
            ..Default::default()
        };
        let recent = Run {
            run_id: "new".into(),
            started: "2026".into(),
            metrics: vec![metric("tool/2.0", 50.0)],
            ..old.clone()
        };
        let text = render(&[old, recent], &Baselines::new());
        assert!(text.contains("50.0"));
        assert!(!text.contains("9 999"));
        assert_eq!(number(-12345.0), "-12 345");
        assert_eq!(render(&[], &Baselines::new()), "");
    }
}
