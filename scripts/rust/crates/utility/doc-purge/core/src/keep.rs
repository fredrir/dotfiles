//! Which comments survive a purge.
//!
//! Two global tables plus each descriptor's `directives`. The split is
//! load-bearing: `safety:` documents an unsafe block and this workspace denies
//! `clippy::undocumented_unsafe_blocks`, so it must survive — but only where it
//! opens the comment. Anywhere else it is prose and goes.

use crate::lang::Dialect;
use crate::scan::Comment;

const BOM: &[u8] = b"\xef\xbb\xbf";

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kept {
    Shebang,
    Important,
    Directive,
    License,
}

/// Matched at the trimmed body start, any language.
const GLOBAL_OPENINGS: &[&str] = &[
    // Prose that carries intent, and the Rust/clippy family that must outlive a
    // purge. `// this is a safety: note` is prose, not a directive, so these are
    // deliberately not in `GLOBAL_ANYWHERE`.
    "safety:",
    "panics:",
    "invariant:",
    "safety-proof:",
    "note:",
    "todo:",
    "fixme:",
    "hack:",
    "xxx:",
    "nb:",
    "caveat:",
    "important:",
    "warning:",
    "why:",
    "rationale:",
    // Ecosystem markers that no descriptor declares. Kept global until one
    // does; each belongs in a `syntax.directives` table.
    "@formatter:",
    "-*-",
    "-@",
    "$non-nls-",
];

/// Matched anywhere in the body, any language: provenance notices that stay
/// true wherever they sit.
const GLOBAL_ANYWHERE: &[&str] = &[
    "do not edit",
    "code generated by",
    "sourcemappingurl",
    "sourceurl",
    "spdx-license-identifier",
];

const LICENCES: &[&str] = &[
    "spdx-license-identifier",
    "copyright",
    "licensed under",
    "all rights reserved",
    "gnu general public",
    "mit license",
    "apache license",
];

/// The verdict and the marker that produced it, so the CLI can explain a keep.
pub fn kept(
    source: &[u8],
    comment: &Comment,
    dialect: Dialect,
    leading: bool,
) -> Option<(Kept, &'static str)> {
    if starts_hashbang(source, comment) {
        return Some((Kept::Shebang, "#!"));
    }
    if source
        .get(comment.span.start..)
        .is_some_and(|rest| rest.starts_with(b"/*!"))
    {
        return Some((Kept::Important, "/*!"));
    }
    let body = String::from_utf8_lossy(&source[comment.body.clone()]).to_lowercase();
    if body.contains("@license") {
        return Some((Kept::License, "@license"));
    }
    if body.contains("@preserve") {
        return Some((Kept::Directive, "@preserve"));
    }
    let opening = body
        .trim_start()
        .trim_start_matches(['*', '/'])
        .trim_start();
    if let Some(marker) = opening_marker(GLOBAL_OPENINGS, opening) {
        return Some((Kept::Directive, marker));
    }
    if let Some(marker) = anywhere_marker(GLOBAL_ANYWHERE, &body) {
        return Some((Kept::Directive, marker));
    }
    if let Some(marker) = opening_marker(dialect.syntax().directives, opening) {
        return Some((Kept::Directive, marker));
    }
    if leading && let Some(marker) = anywhere_marker(LICENCES, &body) {
        return Some((Kept::License, marker));
    }
    None
}

/// The first marker in `table` that `body` starts with.
fn opening_marker(table: &[&'static str], body: &str) -> Option<&'static str> {
    table
        .iter()
        .copied()
        .find(|marker| starts_with_ci(body, marker))
}

/// The first marker in `table` that occurs in `body`.
fn anywhere_marker(table: &[&'static str], body: &str) -> Option<&'static str> {
    table.iter().copied().find(|marker| body.contains(marker))
}

/// `body` starts with `marker`, ASCII case-insensitively: descriptors are data,
/// so their spelling is not trusted to be lowercase.
fn starts_with_ci(body: &str, marker: &str) -> bool {
    body.get(..marker.len())
        .is_some_and(|head| head.eq_ignore_ascii_case(marker))
}

fn starts_hashbang(source: &[u8], comment: &Comment) -> bool {
    let start = comment.span.start;
    let at_start = start == 0 || (start == BOM.len() && source.starts_with(BOM));
    at_start && source[start..].starts_with(b"#!")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Decide the only comment in `source`: a line comment `marker …` running to
    /// the end of its line.
    fn line(
        source: &str,
        marker: &str,
        dialect: Dialect,
        leading: bool,
    ) -> Option<(Kept, &'static str)> {
        let start = source.find(marker).expect("marker in source");
        let body = start + marker.len();
        let end = source[body..]
            .find('\n')
            .map_or(source.len(), |at| body + at);
        let comment = Comment {
            span: start..end,
            body: body..end,
        };
        kept(source.as_bytes(), &comment, dialect, leading)
    }

    /// Decide the only comment in `source`: a block comment `open … close`.
    fn block(
        source: &str,
        open: &str,
        close: &str,
        dialect: Dialect,
    ) -> Option<(Kept, &'static str)> {
        let start = source.find(open).expect("open in source");
        let body = start + open.len();
        let end = body + source[body..].find(close).expect("close in source");
        let comment = Comment {
            span: start..end + close.len(),
            body: body..end,
        };
        kept(source.as_bytes(), &comment, dialect, false)
    }

    #[test]
    fn safety_at_body_start_is_kept() {
        let source = "fn f() {\n    // SAFETY: the pointer is valid\n    unsafe {}\n}\n";
        assert_eq!(
            line(source, "//", Dialect::Rust, false),
            Some((Kept::Directive, "safety:"))
        );
    }

    #[test]
    fn safety_mid_body_is_purged() {
        let source = "// this is a safety: note about the lock order\n";
        assert_eq!(line(source, "//", Dialect::Rust, false), None);
    }

    #[test]
    fn safety_in_block_comment_is_kept() {
        let source = "/* SAFETY: the pointer is valid */\n";
        assert_eq!(
            block(source, "/*", "*/", Dialect::Rust),
            Some((Kept::Directive, "safety:"))
        );
    }

    #[test]
    fn prose_markers_at_body_start_are_kept() {
        for (written, marker) in [
            ("NOTE", "note:"),
            ("TODO", "todo:"),
            ("FIXME", "fixme:"),
            ("HACK", "hack:"),
        ] {
            let source = format!("// {written}: later\n");
            assert_eq!(
                line(&source, "//", Dialect::Rust, false),
                Some((Kept::Directive, marker)),
                "{written}"
            );
        }
    }

    #[test]
    fn go_directive_is_scoped_to_go() {
        let source = "// go:critical this runs once\n";
        assert_eq!(
            line(source, "//", Dialect::Go, false),
            Some((Kept::Directive, "go:"))
        );
        assert_eq!(line(source, "//", Dialect::Rust, false), None);
        assert_eq!(line("// see go:critical\n", "//", Dialect::Go, false), None);
    }

    #[test]
    fn python_directive_is_scoped_to_python() {
        let source = "# type: ignore\nx = 1\n";
        assert_eq!(
            line(source, "#", Dialect::Python, false),
            Some((Kept::Directive, "type:"))
        );
        assert_eq!(line(source, "#", Dialect::Ruby, false), None);
    }

    #[test]
    fn license_marker_is_kept() {
        let source = "// @license MIT\n";
        assert_eq!(
            line(source, "//", Dialect::Rust, false),
            Some((Kept::License, "@license"))
        );
    }

    #[test]
    fn important_block_is_kept() {
        let source = "/*! banner */\ncode\n";
        assert_eq!(
            block(source, "/*!", "*/", Dialect::Css),
            Some((Kept::Important, "/*!"))
        );
    }

    #[test]
    fn shebang_is_kept() {
        let source = "#!/usr/bin/env python\nprint(1)\n";
        let end = source.find('\n').expect("newline");
        let comment = Comment {
            span: 0..end,
            body: 2..end,
        };
        assert_eq!(
            kept(source.as_bytes(), &comment, Dialect::Python, false),
            Some((Kept::Shebang, "#!"))
        );
    }

    #[test]
    fn plain_note_is_purged() {
        let source = "// note about the loop\n";
        assert_eq!(line(source, "//", Dialect::Rust, false), None);
    }

    #[test]
    fn css_directive_is_scoped_to_the_style_family() {
        let source = "/* stylelint-disable-next-line */\na {}\n";
        assert_eq!(
            block(source, "/*", "*/", Dialect::Css),
            Some((Kept::Directive, "stylelint"))
        );
        assert_eq!(block(source, "/*", "*/", Dialect::Rust), None);
    }
}
